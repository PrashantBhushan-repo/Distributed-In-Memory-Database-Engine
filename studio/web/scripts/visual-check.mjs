import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:3000/');
await page.getByRole('textbox', { name: 'Redis demo command' }).waitFor();
await page.screenshot({ path: 'artifacts/landing-desktop.png', fullPage: true });
await page.screenshot({ path: 'artifacts/landing-hero.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'artifacts/landing-mobile.png', fullPage: true });
await page.screenshot({ path: 'artifacts/landing-mobile-hero.png' });
console.log(JSON.stringify({ errors, overflow: await page.evaluate(() => document.documentElement.scrollWidth > innerWidth) }));
await page.goto('http://localhost:3000/social-card.svg');
await page.setViewportSize({ width: 1200, height: 675 });
await page.locator('svg').screenshot({ path: 'public/social-card.png' });
await browser.close();
